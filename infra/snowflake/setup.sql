-- StreamForge Snowflake setup (M4). Idempotent: safe to re-run.
--
-- Run with:  python -m streamforge.admin.snowflake_setup apply
-- Requires a user holding ACCOUNTADMIN (resource monitors are ACCOUNTADMIN-only).
-- Each step switches to the narrowest system role able to perform it.
-- {{APP_USER}} is replaced by the runner with SNOWFLAKE_USER (validated identifier).
-- Touches only StreamForge objects; no other database, warehouse or role is modified.

USE SECONDARY ROLES NONE;

-- 1. Application role (roles are created by USERADMIN)
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS STREAMFORGE_ROLE
  COMMENT = 'StreamForge application role (least privilege)';

-- 2. Warehouse and database, owned by SYSADMIN
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS STREAMFORGE_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'StreamForge compute';
-- Re-assert the cost settings (no-op when unchanged; does not resume the warehouse)
ALTER WAREHOUSE STREAMFORGE_WH SET
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 300;

CREATE DATABASE IF NOT EXISTS ECOMMERCE_STREAMING_DB
  DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'StreamForge e-commerce streaming data';
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_STREAMING_DB.RAW
  COMMENT = 'Append-only events as ingested from Kafka';
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_STREAMING_DB.STAGING
  COMMENT = 'Validated, deduplicated, typed records';
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_STREAMING_DB.ANALYTICS
  COMMENT = 'Business-ready facts, dimensions and aggregates';
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_STREAMING_DB.OPS
  COMMENT = 'Operational metadata: load audit, reconciliation, checks';

-- 3. Cost guardrail: resource monitor on the StreamForge warehouse only
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS STREAMFORGE_MONITOR
  WITH CREDIT_QUOTA = 5
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 50 PERCENT DO NOTIFY
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE STREAMFORGE_WH SET RESOURCE_MONITOR = STREAMFORGE_MONITOR;

-- 4. Least-privilege grants (SECURITYADMIN holds MANAGE GRANTS)
USE ROLE SECURITYADMIN;
GRANT ROLE STREAMFORGE_ROLE TO ROLE SYSADMIN;
GRANT ROLE STREAMFORGE_ROLE TO USER {{APP_USER}};

GRANT USAGE, OPERATE ON WAREHOUSE STREAMFORGE_WH TO ROLE STREAMFORGE_ROLE;
GRANT USAGE ON DATABASE ECOMMERCE_STREAMING_DB TO ROLE STREAMFORGE_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ECOMMERCE_STREAMING_DB.RAW TO ROLE STREAMFORGE_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ECOMMERCE_STREAMING_DB.STAGING TO ROLE STREAMFORGE_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ECOMMERCE_STREAMING_DB.ANALYTICS TO ROLE STREAMFORGE_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ECOMMERCE_STREAMING_DB.OPS TO ROLE STREAMFORGE_ROLE;
-- Bulk loading into RAW (write_pandas uses a temporary stage and file format)
GRANT CREATE STAGE, CREATE FILE FORMAT ON SCHEMA ECOMMERCE_STREAMING_DB.RAW TO ROLE STREAMFORGE_ROLE;
